#!/usr/bin/env python3
"""Deterministic, DPI-ready Atelier installer plates; no runtime installer changes.

The existing A silhouette feeds one connected ink channel into a Krackle seal.
All copy remains native wizard text, so it scales and is available to accessibility.
Run this script to regenerate assets; use --check to verify packaged pixels.
"""
import argparse
import io
from pathlib import Path

from PIL import Image, ImageDraw

import brand_mark

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'gui' / 'brand' / 'installer'
BLUE = '#5487db'
RIFT = '#8a6cff'
THEMES = {'light': '#eee5cf', 'dark': '#121216'}
ROUTE = [('M', 111, 134), ('L', 111, 146), ('Q', 111, 164, 93, 164),
         ('L', 59, 164), ('Q', 39, 164, 39, 184), ('L', 39, 207),
         ('Q', 39, 229, 61, 229), ('L', 107, 229), ('Q', 129, 229, 129, 251),
         ('L', 129, 263)]
SEAL = [(46, 256, 138, 278, 10), (35, 261, 63, 278, 8), (55, 252, 86, 278, 10)]
HOLES = [(122, 269, 4), (114, 273, 2.8), (130, 264, 2.5),
         (111, 264, 1.7), (102, 273, 1.3)]


def route_points():
    points = []
    for command in ROUTE:
        if command[0] in ('M', 'L'):
            points.append(command[1:])
        else:
            x, y = points[-1]
            _, cx, cy, ex, ey = command
            for step in range(1, 65):
                t = step / 64
                points.append(((1-t)**2*x+2*(1-t)*t*cx+t*t*ex,
                               (1-t)**2*y+2*(1-t)*t*cy+t*t*ey))
    return points


def plate(theme):
    # 4x output supplies crisp edges well beyond 200% Windows scaling.
    factor = 8
    bg = THEMES[theme]
    image = Image.new('RGB', (164*factor, 314*factor), bg)
    draw = ImageDraw.Draw(image)
    points = [(x*factor, y*factor) for x, y in route_points()]
    draw.line(points, fill=BLUE, width=12*factor, joint='curve')
    # Union round disks at every curve sample: Pillow's thick polyline joins can
    # otherwise leave hairline wedges between subpixel segments.
    for x, y in points:
        draw.ellipse((x-6*factor, y-6*factor, x+6*factor, y+6*factor), fill=BLUE)
    # The original mark is generated from its source geometry, not a resized icon.
    mark = brand_mark.raster(100*factor, 'full')
    image.paste(mark, (32*factor, 42*factor), mark)
    for x0, y0, x1, y1, radius in SEAL:
        draw.rounded_rectangle((x0*factor, y0*factor, x1*factor, y1*factor), radius*factor, fill=RIFT)
    for x, y, radius in HOLES:
        draw.ellipse(((x-radius)*factor, (y-radius)*factor, (x+radius)*factor, (y+radius)*factor), fill=bg)
    # One upstream bubble belongs to the channel itself.
    draw.ellipse((34*factor, 187*factor, 41*factor, 194*factor), fill=bg)
    return image.resize((656, 1256), Image.Resampling.LANCZOS)


def vector(theme):
    route = ' '.join(part[0]+' '.join(map(str, part[1:])) for part in ROUTE)
    holes = ''.join(f' M{x-r} {y}a{r} {r} 0 1 0 {r*2} 0a{r} {r} 0 1 0 {-r*2} 0Z'
                    for x, y, r in brand_mark.bubbles('full'))
    rectangles = ''.join(f'<rect x="{x0}" y="{y0}" width="{x1-x0}" height="{y1-y0}" rx="{r}"/>'
                         for x0, y0, x1, y1, r in SEAL)
    cutouts = ''.join(f'<circle cx="{x}" cy="{y}" r="{r}"/>' for x, y, r in HOLES)
    return ('<!-- Generated by scripts/installer_art.py; text stays native. -->\n'
            '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 164 314">'
            f'<rect width="164" height="314" fill="{THEMES[theme]}"/>'
            f'<path d="{route}" fill="none" stroke="{BLUE}" stroke-width="12" stroke-linecap="round" stroke-linejoin="round"/>'
            f'<path transform="translate(32 42)" d="{brand_mark.outline_path()}{holes}" fill="{BLUE}" fill-rule="evenodd"/>'
            f'<g fill="{RIFT}">{rectangles}</g><g fill="{THEMES[theme]}">{cutouts}<circle cx="37.5" cy="190.5" r="3.5"/></g></svg>\n')


def png(image):
    output = io.BytesIO()
    image.save(output, 'PNG', optimize=True)
    return output.getvalue()


def outputs():
    result = {}
    for theme in THEMES:
        result[f'wizard-{theme}.png'] = png(plate(theme))
        result[f'wizard-{theme}.svg'] = vector(theme).encode()
    small = Image.new('RGBA', (256, 256))
    mark = brand_mark.raster(224, 'full')
    small.paste(mark, (16, 16), mark)
    result['wizard-mark.png'] = png(small)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    options = parser.parse_args()
    expected = outputs()
    if options.check:
        stale = [name for name, data in expected.items() if not (OUT/name).exists() or (OUT/name).read_bytes() != data]
        if stale:
            raise SystemExit('Installer artwork is out of date: '+', '.join(stale))
        print('Installer artwork up to date')
    else:
        OUT.mkdir(parents=True, exist_ok=True)
        for name, data in expected.items():
            (OUT/name).write_bytes(data)
        print(f'Wrote {len(expected)} installer artwork files')


if __name__ == '__main__':
    main()
