'use strict';
const assert = require('node:assert/strict');
const D = require('../gui/vfx-motionboard-data.js');
const named = (name, channels, index) => ({channels, export_indices:[index], stops:[[1,1,1,1]],
  bindings:[{source:'binding',names:[name]}]});
assert.deepEqual(D.sample([[0,-2],[2,4]],.25),[.5,-.5]);
assert.deepEqual(D.sample([[3]],.9),[3]);
assert.deepEqual(D.sample([[0],[1]],-1),[0]);
assert.deepEqual(D.sample([[0],[1]],2),[1]);
const color=named('Sparks.ScaleColor.ColorScale',4,1), alpha=named('Sparks.ScaleColor.AlphaScale',1,2);
assert.equal(D.binding(color).role,'color'); assert.equal(D.binding(alpha).role,'opacity');
assert.equal(D.binding(named('Sparks.ScaleSpriteSize.Uniform Curve Sprite Scale',2,3)).role,'scale');
assert.equal(D.binding(named('Sparks.SpawnRate.SpawnRate',1,4)).role,'rate');
assert.equal(D.binding(named('Sparks.Emissive.EmissiveColor',4,5)).role,'emission');
assert.equal(D.binding({channels:4,kind:'opacity',bindings:[{source:'owner',label:'Emitter.OpacityCurve',names:[]}]}).role,null);
assert.equal(D.binding(named('Unknown.SelectFloatFromArray.Float Selection Array',1,6)).role,null);
const mixed={...color,bindings:[...color.bindings,{source:'binding',names:['Sparks.ScaleColor.AlphaScale']}]};
assert.equal(D.binding(mixed).source,'ambiguous');
assert.equal(D.assignments([color,{...color,export_indices:[7]}]).values.color,'');
assert.equal(D.assignments([color,alpha]).values.opacity,'2');
const original=[[0],[.75],[1]], group={channels:1,stops:[[0],[1]],original_stops:[[0],[1]],original_samples:original,has_saved_edit:false};
assert.strictEqual(D.edited(group),original);
assert.equal(D.sample(D.edited(group),.5)[0],.75);
group.has_saved_edit=true;
assert.strictEqual(D.edited(group),group.stops);
group.restore_original=true;
assert.strictEqual(D.edited(group),original);
assert.equal(D.allowed('color',{channels:2}),false);
assert.equal(D.allowed('opacity',{channels:3}),false);
console.log('PASS Motionboard sampling, pristine references, named/mixed/ambiguous bindings and dimension-aware proxy assignments');
