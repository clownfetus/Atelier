/*
 * Atelier — Krackle setup drop (identity v1.0)
 * Classic-script IIFE adding window.AtelierMotion.setupDrop.
 *
 * First-run setup ends on the export review's ink-well (AtelierMotion.inkWell), whose label is
 * the page's own Open Atelier button. One drop of ink follows a dotted line down the rows' glyph
 * column, from above the first row, past each row, and into the well's mouth. Its stops are the
 * row boundaries:
 *   station 0        above the first row, where the drop forms
 *   station k        under row k, reached once rows 1..k are all valid
 *   the well         after the last row, once every row is valid: the drop gathers, arcs over
 *                    and plunges into the mouth, and the well performs its success as it enters
 *                    (the ink washes through, a squeeze, a clean burst, then calm)
 * The well's lid is its status: shut in the energy ink while rows need the person, and once
 * every row is valid it takes the done colour and swings open about its left cap as the drop
 * gathers, before the drop falls in.
 * The drop waits under the last valid row, at the first one that is not. While that row is
 * being fetched it charges on the beat; while it needs the person it rests. The well is alive
 * the whole time, cooking as it does in the export review, until the drop lands. The line it has
 * travelled is inked; the line ahead is plain.
 *
 * mount(host, {layer, size}) returns setProgress(reached, {rows, glyphs, waiting}) and destroy.
 * `host` is the well's empty slot; `reached` counts the valid rows from the top; `rows` and
 * `glyphs` are the rows in page order and their glyph hosts; `waiting` is 'busy' or 'still';
 * `layer` is the positioned page the line is drawn across. The application owns validation; this
 * file makes no API or storage calls and never holds a result back. Moving forward travels,
 * continuing whatever is already moving; a row losing its validity interrupts: the drop is placed
 * at once and the well cooks again. Travel is Full motion only: Calm, Off, reduced motion, a
 * hidden document or missing Web Animations place the drop and show the well's still poses.
 * Artwork is generated by scripts/krackle_art.py; the well is ink-well.js, mounted as it is.
 */
(function () {
  'use strict';

  var P = 'am-setup-drop';
  var NS = 'http://www.w3.org/2000/svg';
  // The ink-well's mouth, as a fraction of its square SVG (rim centre in its 10 10 236 236 view).
  var MOUTH = {x: (129.5 - 10) / 236, y: (50.3 - 10) / 236};
  // The rim's centre and top, as fractions of the well, for the lid; the lid art is drawn for
  // the page's 240px well (LID in scripts/krackle_art.py) and scales with the well.
  var RIM = {x: (130 - 10) / 236, top: (51.5 - 9.6 - 10) / 236};
  var LID = {w: 108, h: 23, drawnFor: 240, lift: 4};
  var DOT_STEP = 15, CLEAR = 5;      // the line's dot spacing and its gap around each glyph
  var mounted = typeof WeakMap === 'function' ? new WeakMap() : null;

  // krackle-art:setup-drop:begin
  var SVG_MARKUP = '<svg xmlns="http://www.w3.org/2000/svg" class="am-setup-drop-svg" viewBox="-7 -14 130 30" width="130" height="30" aria-hidden="true" focusable="false" fill="currentColor"><g class="am-setup-drop-drop"><path class="am-setup-drop-energy" d="M0 -13 C2.52 -7.54 6 -3.72 6 0 A6 6 0 1 1 -6 0 C-6 -3.72 -2.52 -7.54 0 -13 Z" /><circle class="am-setup-drop-glint" cx="-2.2" cy="-1.6" r="1.3" /></g><circle class="am-setup-drop-dot" cx="0" cy="12" r="1.8" /><svg class="am-setup-drop-lid" viewBox="0 0 108 23" width="108" height="23" x="14" y="-14" overflow="visible"><g class="am-setup-drop-lid-swing"><path class="am-setup-drop-lid-energy" d="M42 10 V6 Q42 0 48 0 H60 Q66 0 66 6 V10 Z" /><rect class="am-setup-drop-lid-energy" x="0" y="7" width="108" height="16" rx="8" /></g></svg></svg>';
  // krackle-art:setup-drop:end

  function full() {
    if (document.documentElement.dataset.motion === 'reduce') return false;
    if (window.AtelierMotionPolicy) return window.AtelierMotionPolicy.allows(3);
    try { return !window.matchMedia('(prefers-reduced-motion: reduce)').matches; } catch (_) { return true; }
  }
  function bezier(a, b, c, d, t) { var u = 1 - t; return u * u * u * a + 3 * u * u * t * b + 3 * u * t * t * c + t * t * t * d; }
  // The identity's curves, read from the host's surface: pop for forming, gather for charging,
  // pour for travel; fall is the motion core's gravity.
  var EASE_FALLBACK = {pop: 'cubic-bezier(.34, 1.56, .64, 1)', gather: 'cubic-bezier(.55, 0, .8, .35)', pour: 'cubic-bezier(.25, .1, .15, 1)'};
  function easings(host) {
    var out = {fall: (window.AtelierMotion.ease && window.AtelierMotion.ease.fall) || 'cubic-bezier(.55, 0, 1, .45)'}, style = null;
    try { style = getComputedStyle(host); } catch (_) {}
    Object.keys(EASE_FALLBACK).forEach(function (name) {
      var token = style && style.getPropertyValue('--ease-' + name).trim();
      out[name] = token || EASE_FALLBACK[name];
    });
    return out;
  }

  function mount(host, options) {
    if (!host || host.nodeType !== 1) throw new Error('AtelierMotion.setupDrop.mount requires a DOM host.');
    var prior = mounted && mounted.get(host);
    if (prior) prior.destroy();
    if (host.childNodes.length) throw new Error('Setup drop needs an empty host.');
    if (!SVG_MARKUP) throw new Error('Setup drop artwork is missing.');

    var opts = options || {};
    var layer = opts.layer && opts.layer.nodeType === 1 ? opts.layer : null;
    var ease = easings(host);
    var destroyed = false, rows = [], glyphs = [], waiting = 'still';
    var at = 0, target = 0, filled = false, moving = false, running = [];
    var stations = [], mouth = null, dots = [], arc = [];
    host.setAttribute('data-atelier-motion', 'setup-drop');
    var art = document.createElement('template');
    art.innerHTML = SVG_MARKUP;
    var dropArt = art.content.querySelector('.' + P + '-drop');
    var dotArt = art.content.querySelector('.' + P + '-dot');
    var lidArt = art.content.querySelector('.' + P + '-lid');

    // The receiving well is the ink-well itself, cooking until the drop lands. Without it the
    // drop still travels and lands; there is just no burst.
    var wellHost = document.createElement('span');
    wellHost.className = P + '-well';
    host.appendChild(wellHost);
    var well = null, size = Number(opts.size) || 240;
    try {
      well = window.AtelierMotion.inkWell.mount(wellHost, {size: size, kind: 'setup', state: 'busy', fixedFrame: true, sparse: true,
        reducedMotion: full() ? 'system' : 'reduce'});
    } catch (_) { well = null; }
    // The lid sits over the mouth, hinged at its left cap; its pose and colour follow data-am-lid.
    var lid = null, swing = null, k = size / LID.drawnFor;
    if (lidArt) {
      lid = lidArt.cloneNode(true);
      lid.setAttribute('width', String(LID.w * k)); lid.setAttribute('height', String(LID.h * k));
      lid.setAttribute('aria-hidden', 'true'); lid.setAttribute('focusable', 'false');
      lid.style.left = (size * RIM.x - LID.w * k / 2).toFixed(1) + 'px';
      lid.style.top = (size * RIM.top - (LID.h + LID.lift) * k).toFixed(1) + 'px';
      swing = lid.querySelector('.' + P + '-lid-swing');
      wellHost.appendChild(lid);
    }
    function lidState(open) { host.setAttribute('data-am-lid', open ? 'open' : 'shut'); }
    // Opening: it takes the done colour and swings about its left cap, overshooting once.
    function openLid() {
      lidState(true);
      if (!swing) return;
      var style = null;
      try { style = getComputedStyle(host); } catch (_) {}
      var from = style && style.getPropertyValue('--energy').trim(), to = style && style.getPropertyValue('--done').trim();
      if (from && to) animate(lid, [{color: from}, {color: to}], {duration: 260, easing: ease.pour});
      animate(swing, [
        {transform: 'rotate(0deg)', offset: 0, easing: ease.pop}, {transform: 'rotate(-150deg)', offset: .55, easing: ease.pop},
        {transform: 'rotate(-132deg)', offset: .78, easing: ease.pop}, {transform: 'rotate(-138deg)', offset: 1}
      ], {duration: 620, easing: 'linear'});
    }

    // The line and the drop live in the page, beneath the rows (the drop passes behind each
    // row's glyph) and the well.
    var overlay = null, line = null, flier = null, body = null;
    function el(name, cls) { var node = document.createElementNS(NS, name); if (cls) node.setAttribute('class', cls); return node; }
    if (layer) {
      overlay = el('svg', P + '-flight');
      overlay.setAttribute('aria-hidden', 'true');
      overlay.setAttribute('focusable', 'false');
      line = el('g', P + '-line');
      flier = el('g', P + '-flier'); body = el('g', P + '-flier-body');
      body.appendChild(dropArt.cloneNode(true)); flier.appendChild(body);
      overlay.appendChild(line); overlay.appendChild(flier);
      layer.appendChild(overlay);
    }

    function last() { return rows.length; }
    function measure() {
      if (destroyed || !overlay || !rows.length) return false;
      var base = layer.getBoundingClientRect(), box = (wellHost.querySelector('svg') || wellHost).getBoundingClientRect();
      var g = glyphs[0] && glyphs[0].getBoundingClientRect();
      if (!g || !g.width || !box.width) return false;
      var x = g.left + g.width / 2 - base.left;
      stations = [];
      for (var i = 0; i <= rows.length; i++) {
        var r = rows[Math.min(i, rows.length - 1)].getBoundingClientRect();
        stations.push({x: x, y: (i < rows.length ? r.top : r.bottom) - base.top});
      }
      mouth = {x: box.left + MOUTH.x * box.width - base.left, y: box.top + MOUTH.y * box.height - base.top};
      // Past the last row the line leaves the column straight down and arrives in the mouth from
      // straight above: an S between the two.
      var end = stations[stations.length - 1], d = Math.max(0, (mouth.y - end.y) / 2);
      arc = [];
      for (var k = 0; k <= 24; k++) {
        var t = k / 24;
        arc.push({x: bezier(end.x, end.x, mouth.x, mouth.x, t), y: bezier(end.y, end.y + d, mouth.y - d, mouth.y, t)});
      }
      drawLine(base);
      return true;
    }
    // Dots every DOT_STEP down the column, parting around each glyph, then along the arc.
    function drawLine(base) {
      while (line.firstChild) line.removeChild(line.firstChild);
      dots = [];
      var boxes = glyphs.map(function (glyph) {
        var r = glyph.getBoundingClientRect();
        return {top: r.top - base.top - CLEAR, bottom: r.bottom - base.top + CLEAR};
      });
      var top = stations[0], end = stations[stations.length - 1];
      function add(x, y) {
        var dot = dotArt.cloneNode(true);
        dot.setAttribute('cx', x.toFixed(1)); dot.setAttribute('cy', y.toFixed(1));
        line.appendChild(dot); dots.push({node: dot, y: y});
      }
      for (var y = top.y; y < end.y; y += DOT_STEP) {
        if (!boxes.some(function (b) { return y > b.top && y < b.bottom; })) add(top.x, y);
      }
      // Along the arc by distance, stopping a step short of the mouth so no dot sits on the rim.
      var run = 0, next = DOT_STEP;
      for (var i = 1; i < arc.length; i++) {
        var seg = Math.hypot(arc[i].x - arc[i - 1].x, arc[i].y - arc[i - 1].y);
        while (run + seg >= next) {
          var f = (next - run) / seg, px = arc[i - 1].x + (arc[i].x - arc[i - 1].x) * f, py = arc[i - 1].y + (arc[i].y - arc[i - 1].y) * f;
          if (Math.hypot(mouth.x - px, mouth.y - py) > DOT_STEP * 1.5) add(px, py);
          next += DOT_STEP;
        }
        run += seg;
      }
      inkTo(filled ? Infinity : stations[at].y);
    }
    function inkTo(y) { dots.forEach(function (d) { d.node.classList.toggle('is-inked', d.y <= y + 0.5); }); }

    function translate(p) { return 'translate(' + p.x.toFixed(1) + 'px, ' + p.y.toFixed(1) + 'px)'; }
    function put(p) { flier.style.transform = translate(p); }
    // The well cooks until the drop is in, performs its success once it is, and cooks again
    // if a row is lost. It is told the motion setting each time, so it shows its still poses
    // whenever the drop is placed rather than travelled.
    function wellState(state) {
      if (!well) return;
      well.setReducedMotion(full() ? 'system' : 'reduce');
      well.setState(state);
    }
    function sync() {
      if (destroyed) return;
      host.setAttribute('data-am-reached', String(at));
      host.setAttribute('data-am-full', String(filled));
      host.setAttribute('data-am-moving', String(moving));
      if (overlay) {
        overlay.setAttribute('data-am-waiting', !filled && !moving && at < last() ? waiting : 'none');
        flier.style.visibility = filled || !stations.length ? 'hidden' : '';
      }
      if (!moving) { wellState(filled ? 'success' : 'busy'); lidState(filled); }
    }
    function animate(node, frames, timing) {
      if (!node || typeof node.animate !== 'function') return null;
      try { var a = node.animate(frames, timing); running.push(a); return a; } catch (_) { return null; }
    }
    function cancel() {
      running.forEach(function (a) { try { a.cancel(); } catch (_) {} });
      running = [];
      moving = false;
    }
    // Staged motion: each stage moves the flier along `path` (points) and shapes `body`
    // (keyframes) for `dur`, then the next begins; `at` is called as the stage starts. Without
    // Web Animations each stage completes at once. Cancelling drops the rest of the chain.
    function chain(stages, done) {
      var i = 0;
      function next() {
        if (destroyed) return;
        if (i >= stages.length) return done();
        var st = stages[i++];
        if (st.at) st.at();
        if (st.path) {
          animate(flier, st.path.map(function (p) { return {transform: translate(p)}; }), {duration: st.dur, easing: st.easing});
          put(st.path[st.path.length - 1]);
        }
        var a = animate(body, st.body, {duration: st.dur, easing: st.bodyEasing || st.easing});
        if (a) a.onfinish = next; else next();
      }
      next();
    }
    // Final pose: the drop at its station, or gone into the well.
    function settleNow() {
      cancel();
      at = target;
      filled = rows.length > 0 && target >= last();
      if (stations.length) { put(stations[Math.min(at, last())]); inkTo(filled ? Infinity : stations[at].y); }
      sync();
    }

    // One station down the line: the drop stretches as it runs and inks the line behind it.
    function step() {
      var from = stations[at], to = stations[at + 1], dur = Math.max(260, Math.min(520, (to.y - from.y) * 5));
      moving = true; sync();
      chain([{dur: dur, easing: ease.pour, path: [from, to], body: [{transform: 'none'}, {transform: 'scale(.86, 1.22)', offset: .45}, {transform: 'none'}]}],
        function () { at++; inkTo(stations[at].y); advance(); });
    }
    // Past the last row: the drop gathers at its station, runs the arc gathering speed, and
    // plunges into the mouth, shrinking into the hole rather than vanishing. The well's success
    // starts as the drop crosses the rim: the ink washes through it, it squeezes, a clean
    // burst leaves the mouth, and it settles calm.
    function fall() {
      moving = true; sync();
      var into = {x: mouth.x, y: mouth.y + 7};
      chain([
        {dur: 140, easing: ease.gather, at: openLid, body: [{transform: 'none'}, {transform: 'scale(1.18, .84)', offset: .55}, {transform: 'scale(.9, 1.16)'}]},
        {dur: 360, easing: 'cubic-bezier(.45, 0, .85, .5)', bodyEasing: ease.fall, path: arc, at: function () { inkTo(Infinity); },
          body: [{transform: 'scale(.9, 1.16)'}, {transform: 'scale(.92, 1.12)', offset: .5}, {transform: 'scale(.76, 1.36)'}]},
        {dur: 90, easing: 'cubic-bezier(.45, 0, 1, 1)', path: [mouth, into], at: function () { wellState('success'); },
          body: [{transform: 'scale(.76, 1.36)'}, {transform: 'scale(.4, .6)'}]}
      ], function () { filled = true; moving = false; sync(); });
    }
    function advance() {
      if (destroyed) return;
      if (at < target && at < last()) return step();
      if (at >= last() && target >= last() && !filled) return fall();
      moving = false; sync();
      if (dirty) relayout();
    }

    function setProgress(reached, info) {
      if (destroyed) return;
      info = info || {};
      if (info.rows) rows = Array.prototype.slice.call(info.rows);
      if (info.glyphs) glyphs = Array.prototype.slice.call(info.glyphs);
      waiting = info.waiting === 'busy' ? 'busy' : 'still';
      var next = Math.max(0, Math.min(rows.length, Math.round(Number(reached) || 0)));
      var first = !stations.length;
      if (!measure()) { target = next; settleNow(); return; }
      var canTravel = full() && !document.hidden && typeof flier.animate === 'function';
      // Results interrupt: going back (or no motion) places the drop at once and a landed well
      // cooks again.
      if (!canTravel || next < at || (filled && next < last())) { target = next; settleNow(); return; }
      target = next;
      if (first) {
        put(stations[at]); inkTo(stations[at].y);
        animate(body, [{transform: 'scale(.2)'}, {transform: 'none'}], {duration: 200, easing: ease.pop});
      }
      if (moving) { sync(); return; }   // already travelling: it carries on to the new target
      advance();
    }

    // Layout changes (a row opening its field, fonts arriving, a resize) move the rows without
    // necessarily resizing the page, so every part of the page is watched. A moving drop is
    // re-placed when it next rests.
    var dirty = false;
    function relayout() {
      if (destroyed || !rows.length) return;
      if (moving) { dirty = true; return; }
      dirty = false;
      if (measure()) put(stations[Math.min(at, last())]);
    }
    var resize = typeof ResizeObserver === 'function' && layer ? new ResizeObserver(relayout) : null;
    if (resize) Array.prototype.forEach.call(layer.children, function (child) { if (child !== overlay) resize.observe(child); });
    if (document.fonts && document.fonts.addEventListener) document.fonts.addEventListener('loadingdone', relayout);
    function onEnvironment() { if (!destroyed && (!full() || document.hidden) && (moving || at !== target)) settleNow(); else sync(); }
    document.addEventListener('visibilitychange', onEnvironment);
    window.addEventListener('atelier:preferences', onEnvironment);
    sync();

    var handle = {
      setProgress: setProgress,
      destroy: function () {
        if (destroyed) return;
        destroyed = true;
        cancel();
        if (resize) resize.disconnect();
        if (document.fonts && document.fonts.removeEventListener) document.fonts.removeEventListener('loadingdone', relayout);
        if (overlay && overlay.parentNode) overlay.parentNode.removeChild(overlay);
        document.removeEventListener('visibilitychange', onEnvironment);
        window.removeEventListener('atelier:preferences', onEnvironment);
        if (well) well.destroy();
        if (wellHost.parentNode === host) host.removeChild(wellHost);
        ['data-atelier-motion', 'data-am-reached', 'data-am-full', 'data-am-moving', 'data-am-lid'].forEach(function (name) { host.removeAttribute(name); });
        if (mounted && mounted.get(host) === handle) mounted.delete(host);
      }
    };
    if (mounted) mounted.set(host, handle);
    return handle;
  }

  window.AtelierMotion = window.AtelierMotion || {};
  window.AtelierMotion.setupDrop = Object.freeze({mount: mount});
})();
